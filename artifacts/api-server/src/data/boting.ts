export interface House {
  id: string;
  nomorUrut: number;
  namaKepalaKeluarga: string;
  alamat: string;
  rt: string;
  rw: string;
  lat: number;
  lng: number;
  // Status & kondisi
  statusPerubahan: "berubah" | "tidak_berubah";
  kondisiBangunan: string;
  klaster: "K1" | "K2" | "K3";
  jumlahJenisPerubahan: number;
  // Atribut bangunan
  luasBangunan: number | null;
  luasLahan: number | null;
  jeniLantai: string | null;
  jenisDinding: string | null;
  jumlahLantai: number | null;
  jenisAtap: string | null;
  jenisPlafon: string | null;
  pagar: string | null;
  tahunDatang: number | null;
  keterangan: string | null;
  // 7 indikator perubahan spesifik
  perubahanPagar: boolean;
  perubahanLuasBangunan: boolean;
  perubahanJumlahLantai: boolean;
  perubahanJenisLantai: boolean;
  perubahanJenisDinding: boolean;
  perubahanLuasLahan: boolean;
  perubahanJenisAtap: boolean;
}

/** Hitung klaster berdasarkan jumlah jenis perubahan */
function hitungKlaster(jumlah: number): "K1" | "K2" | "K3" {
  if (jumlah === 0) return "K1";
  if (jumlah <= 2) return "K2";
  return "K3";
}

/** Helper builder */
function house(
  partial: Omit<House, "statusPerubahan" | "klaster" | "jumlahJenisPerubahan" | "jenisPlafon"> & {
    jenisPlafon?: string | null;
    perubahanPagar: boolean;
    perubahanLuasBangunan: boolean;
    perubahanJumlahLantai: boolean;
    perubahanJenisLantai: boolean;
    perubahanJenisDinding: boolean;
    perubahanLuasLahan: boolean;
    perubahanJenisAtap: boolean;
  },
): House {
  const jumlah = [
    partial.perubahanPagar,
    partial.perubahanLuasBangunan,
    partial.perubahanJumlahLantai,
    partial.perubahanJenisLantai,
    partial.perubahanJenisDinding,
    partial.perubahanLuasLahan,
    partial.perubahanJenisAtap,
  ].filter(Boolean).length;
  return {
    jenisPlafon: null,
    ...partial,
    jumlahJenisPerubahan: jumlah,
    statusPerubahan: jumlah > 0 ? "berubah" : "tidak_berubah",
    klaster: hitungKlaster(jumlah),
  };
}

